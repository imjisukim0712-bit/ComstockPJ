def font_path(lang, kind):
    name = FONTS.get((lang, kind), FALLBACK[kind])
    p = os.path.join(FONTDIR, name)
    if not os.path.exists(p):
        p = os.path.join(FONTDIR, FALLBACK[kind])
    return p
