def seg_at(t):
    """절대 시각 t가 속한 (인덱스, 구간내부시각)을 돌려준다. 구간 밖이면 (-1, 0)."""
    for i in range(len(SEGMENTS)):
        t0 = T0 + i * SEG_LEN
        if t0 <= t < t0 + SEG_LEN:
            return i, t - t0
    return -1, 0.0


def seg_start(i):
    return T0 + i * SEG_LEN


