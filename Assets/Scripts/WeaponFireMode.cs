/// <summary>
/// 무기가 실제로 공격을 만들어내는 방식. WeaponType(연사/산탄/정밀 등 분류)이나
/// WeaponClass(경/중/근접 - 소켓 장착 제한)와는 완전히 다른 축이다.
///
/// - Projectile : 투사체를 날린다. 대부분의 총기가 여기에 속한다.
/// - Beam       : 발사 순간 방향을 고정한 채 일정 시간 동안 직선 범위에 반복 피해를 준다(플라즈마 캐논).
/// - MeleeSwing : 투사체 없이 총구 앞 부채꼴을 즉시 판정한다(근접무기).
///
/// 근접무기를 짧은 사거리의 투사체로 흉내내면 탄이 0.1초 만에 소멸해 화면에 아무것도
/// 보이지 않으므로, 전용 판정을 따로 둔다.
/// </summary>
public enum WeaponFireMode
{
    Projectile = 0,
    Beam = 1,
    MeleeSwing = 2
}
