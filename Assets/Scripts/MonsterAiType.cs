/// <summary>
/// 좀비 기획서(Ver04) p.10 "좀비 AI 성격값" 4종.
///
/// 공통 규칙(문서에서 각 항목에 반복 명시됨 - "이후엔 추격형과 동일"):
/// - 한 번 플레이어를 감지해 추격을 시작하면, 거리가 <b>감지범위 x2</b> 이상 벌어질 때까지는
///   계속 추격한다(추격 종료 조건).
/// - 추격이 끝나면 원래의 대기 상태(정지/배회)로 돌아간다.
///
/// 성격값별 차이는 두 지점뿐이다:
/// 1) <b>대기 상태에서 무엇을 하는가</b> - 추격형/압박형은 가만히 서서 정찰(전체 감지범위로
///    스캔), 휴식형은 정지, 배회형은 자유롭게 배회한다.
/// 2) <b>깨어나는 조건</b> - 추격형/압박형은 감지범위 안에 들어오면 즉시, 휴식형/배회형은
///    더 좁은 범위(감지범위의 1/10) 안에 들어오거나 피격당해야 깨어난다.
/// 3) <b>추격 방식</b> - 압박형만 플레이어의 예상 이동 방향을 선회 추적하고, 나머지는 현재
///    위치로 직진 추격한다.
/// </summary>
public enum MonsterAiType
{
    Aggressive, // 추격형 - 감지범위 내 발견 즉시 직진 추격
    Pressure,   // 압박형 - 감지범위 내 발견 즉시, 예상 이동 방향으로 선회 추적
    Resting,    // 휴식형 - 정지 상태로 대기, 감지범위 1/10 내 접근 또는 피격 시 깨어나 추격형과 동일하게 행동
    Wandering,  // 배회형 - 자유롭게 배회하며 대기, 조건은 휴식형과 동일
}
